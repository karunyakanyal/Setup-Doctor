test('Phase 2: Express wildcard CORS detection & allowedOrigins resolution', () => {
	// 1. origin: '*'
	const resultStar = buildGraph({
		'package.json': JSON.stringify({ name: 'app', dependencies: { express: '^4.18.2' } }),
		'src/app.js': `const cors = require('cors'); app.use(cors({ origin: '*' }));`,
	})
	assert.equal(resultStar.summary.allRules.find((r) => r.id === 'express-wildcard-cors').count, 1)

	// 2. cors() with no options
	const resultNoOptions = buildGraph({
		'package.json': JSON.stringify({ name: 'app', dependencies: { express: '^4.18.2' } }),
		'src/app.js': `const cors = require('cors'); app.use(cors());`,
	})
	assert.equal(resultNoOptions.summary.allRules.find((r) => r.id === 'express-wildcard-cors').count, 1)

	// 3. origin: true
	const resultTrue = buildGraph({
		'package.json': JSON.stringify({ name: 'app', dependencies: { express: '^4.18.2' } }),
		'src/app.js': `const cors = require('cors'); app.use(cors({ origin: true }));`,
	})
	assert.equal(resultTrue.summary.allRules.find((r) => r.id === 'express-wildcard-cors').count, 1)

	// 4. allowedOrigins array containing '*'
	const resultArrStar = buildGraph({
		'package.json': JSON.stringify({ name: 'app', dependencies: { express: '^4.18.2' } }),
		'src/app.js': `const cors = require('cors'); const allowedOrigins = ['http://localhost', '*']; app.use(cors({ origin: allowedOrigins }));`,
	})
	assert.equal(resultArrStar.summary.allRules.find((r) => r.id === 'express-wildcard-cors').count, 1)

	// 5. Negative: allowedOrigins defined in same file without '*' (Setup-Doctor Backend/src/app.js pattern)
	const resultSafe = buildGraph({
		'package.json': JSON.stringify({ name: 'app', dependencies: { express: '^4.18.2' } }),
		'src/app.js': `
const cors = require('cors');
const defaultAllowedOrigins = ['http://localhost:5173', 'http://127.0.0.1:5173'];
const configuredOrigins = process.env.ALLOWED_ORIGINS ? process.env.ALLOWED_ORIGINS.split(',').map(o => o.trim()) : [];
const allowedOrigins = configuredOrigins.length > 0 ? configuredOrigins : defaultAllowedOrigins;
app.use(cors({ origin: allowedOrigins }));
`,
	})
	assert.equal(resultSafe.summary.allRules.find((r) => r.id === 'express-wildcard-cors').count, 0)
})

