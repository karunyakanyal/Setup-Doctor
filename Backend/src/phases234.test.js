test('Phase 1 & 2: Orphans exemption for virtual modules and declaration files', () => {
	// Virtual module reference: @vite/env -> client/env.ts
	const filesVm = {
		'package.json': JSON.stringify({ name: 'app' }),
		'src/client/client.ts': `import '@vite/env'; export const c = 1;`,
		'src/client/env.ts': `export const env = 'production';`,
		'src/index.ts': `import { c } from './client/client';`,
	}
	const resultVm = buildGraph(filesVm)
	assert.ok(!resultVm.summary.orphans.includes('src/client/env.ts'))

	// Declaration only file: declare statements only
	const filesDecl = {
		'package.json': JSON.stringify({ name: 'app' }),
		'src/types.ts': `
declare const __DEFINES__: Record<string, any>;
export declare function doSomething(): void;
`,
		'src/index.ts': `export const main = 1;`,
	}
	const resultDecl = buildGraph(filesDecl)
	assert.ok(!resultDecl.summary.orphans.includes('src/types.ts'))

	// .d.ts file is exempt
	const filesDts = {
		'package.json': JSON.stringify({ name: 'app' }),
		'src/global.d.ts': `interface Window { customProp: string; }`,
		'src/index.ts': `export const main = 1;`,
	}
	const resultDts = buildGraph(filesDts)
	assert.ok(!resultDts.summary.orphans.includes('src/global.d.ts'))
})
