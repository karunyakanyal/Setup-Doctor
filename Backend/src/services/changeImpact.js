// 10 minute cache for change impact results
const CHANGE_IMPACT_CACHE = new Map()
const CHANGE_IMPACT_CACHE_TTL_MS = 10 * 60 * 1000 // 10 minutes
const MAX_CACHE_ENTRIES = 100

function getCachedChangeImpact(key) {
	if (!key) return null
	const item = CHANGE_IMPACT_CACHE.get(key)
	if (!item) return null
	if (Date.now() > item.expiresAt) {
		CHANGE_IMPACT_CACHE.delete(key)
		return null
	}
	return item.data
}

function setCachedChangeImpact(key, data, ttlMs = CHANGE_IMPACT_CACHE_TTL_MS) {
	if (!key) return
	if (CHANGE_IMPACT_CACHE.has(key)) {
		CHANGE_IMPACT_CACHE.delete(key)
	} else if (CHANGE_IMPACT_CACHE.size >= MAX_CACHE_ENTRIES) {
		const oldest = CHANGE_IMPACT_CACHE.keys().next().value
		CHANGE_IMPACT_CACHE.delete(oldest)
	}
	CHANGE_IMPACT_CACHE.set(key, {
		data,
		expiresAt: Date.now() + ttlMs,
	})
}

function clearChangeImpactCache() {
	CHANGE_IMPACT_CACHE.clear()
}

/**
 * Generates ready-to-paste PR comment markdown summary.
 * Strictly capped at max 60 lines, no secrets, uses "+N more" for lists.
 */
function generateMarkdownSummary({
	owner = '',
	repo = '',
	pullNumber = null,
	riskLevel = 'Low',
	riskReason = '',
	changedFilesCount = 0,
	mappedFilesCount = 0,
	newOrUnmappedCount = 0,
	affectedCount = 0,
	totalCodeFiles = 0,
	percentOfRepo = 0,
	unchangedCount = 0,
	willBreakFindings = [],
	folderRows = [],
	testsReached = [],
	entryPointsReached = [],
	routesReached = [],
	truncated = false,
}) {
	const icon = riskLevel === 'High' ? '🔴' : (riskLevel === 'Medium' ? '🟡' : '🟢')
	const lines = []

	lines.push(`## 🔍 SetupDoctor Change Impact Analysis`)
	lines.push('')
	lines.push(`**Risk Level**: ${icon} **${riskLevel}** — ${riskReason}`)
	lines.push('')
	lines.push(`### 📊 Summary`)
	lines.push(`- **Changed files**: ${changedFilesCount} (${mappedFilesCount} mapped to code graph${newOrUnmappedCount > 0 ? `, ${newOrUnmappedCount} new/unmapped` : ''})${truncated ? ' *(capped at 300)*' : ''}`)
	lines.push(`- **Blast radius**: ${affectedCount} of ${totalCodeFiles} code files (${percentOfRepo}%)`)
	lines.push(`- **Unchanged but affected**: ${unchangedCount} files`)
	lines.push(`- **Tests**: ${testsReached.length > 0 ? `${testsReached.length} test files reach these changes` : '⚠️ No tests reach these files'}`)
	if (entryPointsReached.length > 0 || routesReached.length > 0) {
		lines.push(`- **Entry points / Routes**: ${entryPointsReached.length} entry points, ${routesReached.length} API routes`)
	}

	// Will break
	if (willBreakFindings.length > 0) {
		lines.push('')
		lines.push(`### ⚠️ Will Break (${willBreakFindings.length})`)
		const maxShow = 3
		const shown = willBreakFindings.slice(0, maxShow)
		for (const item of shown) {
			lines.push(`- \`${item.file}\` was ${item.status}, but \`${item.importer}${item.line ? `:${item.line}` : ''}\` still imports it`)
		}
		if (willBreakFindings.length > maxShow) {
			lines.push(`- *+${willBreakFindings.length - maxShow} more broken imports*`)
		}
	}

	// Folder blast radius
	if (folderRows.length > 0) {
		lines.push('')
		lines.push(`### 💥 Blast Radius by Folder`)
		const maxFolders = 5
		const shownFolders = folderRows.slice(0, maxFolders)
		for (const f of shownFolders) {
			lines.push(`- **${f.folder}**: ${f.affected} of ${f.total} files affected (${f.direct} direct, ${f.indirect} indirect)`)
		}
		if (folderRows.length > maxFolders) {
			lines.push(`- *+${folderRows.length - maxFolders} more folders*`)
		}
	}

	// Recommended tests
	lines.push('')
	lines.push(`### 🧪 What to Test`)
	if (testsReached.length > 0) {
		const maxTests = 5
		const shownTests = testsReached.slice(0, maxTests)
		for (const t of shownTests) {
			lines.push(`- \`${t}\``)
		}
		if (testsReached.length > maxTests) {
			lines.push(`- *+${testsReached.length - maxTests} more tests*`)
		}
	} else {
		lines.push(`- ⚠️ No tests touch these files; open affected entry points and routes manually`)
	}

	lines.push('')
	lines.push(`---`)
	lines.push(`*Generated by [SetupDoctor](https://github.com/karunyakanyal/Setup-Doctor)*`)

	let result = lines.join('\n')
	result = redactToken(result)

	// Strictly cap at max 60 lines
	const allLines = result.split('\n')
	if (allLines.length > 60) {
		return allLines.slice(0, 58).concat(['', `*+${allLines.length - 58} more lines omitted*`]).join('\n')
	}
	return result
}

/**
 * Deterministically computes the change impact from graph and changed files.
 */
function computeChangeImpact({
	changedFiles = [],
	baseGraph = { nodes: [], edges: [], summary: {} },
	baseFiles = null,
	owner = '',
	repo = '',
	pullNumber = null,
	baseRef = 'main',
	headSha = '',
	truncated = false,
}) {
	const nodes = baseGraph.nodes || []
	const edges = baseGraph.edges || []
	const totalCodeFiles = nodes.length

	const idToNode = new Map(nodes.map((n) => [n.id, n]))
	const pathToNode = new Map(nodes.map((n) => [n.path, n]))

	// 1. Map changed files to graph nodes
	const mappedFiles = []
	const newOrUnmappedFiles = []
	const changedSet = new Set()

	for (const file of changedFiles) {
		const rawPath = file.filename || file.path || ''
		const cleanPath = rawPath.replace(/^\.\//, '')
		const status = file.status || 'modified'
		const prevRaw = file.previous_filename || file.previousPath || null
		const cleanPrev = prevRaw ? prevRaw.replace(/^\.\//, '') : null

		changedSet.add(cleanPath)
		if (cleanPrev) changedSet.add(cleanPrev)

		// Base lookup: for renamed files, old path is in base; for removed, path is in base; for added, not in base
		const basePath = status === 'renamed' && cleanPrev ? cleanPrev : cleanPath
		const node = pathToNode.get(basePath)

		if (node) {
			mappedFiles.push({
				path: cleanPath,
				basePath,
				status,
				previousPath: cleanPrev,
				node: {
					id: node.id,
					path: node.path,
					lang: node.lang,
					isEntry: node.isEntry,
					isTest: node.isTest,
					category: node.category,
				},
			})
		} else {
			newOrUnmappedFiles.push({
				path: cleanPath,
				status,
				previousPath: cleanPrev,
				reason: status === 'added' ? 'Newly added file in this PR' : 'Not mapped in base code graph',
			})
		}
	}

	// 2. Incoming adjacency list from baseGraph.edges
	const incomingMap = new Map() // toPath -> [fromPath]
	for (const edge of edges) {
		let fromPath, toPath
		if (Array.isArray(edge)) {
			fromPath = typeof edge[0] === 'string' ? edge[0] : idToNode.get(edge[0])?.path
			toPath = typeof edge[1] === 'string' ? edge[1] : idToNode.get(edge[1])?.path
		} else if (edge && typeof edge === 'object') {
			fromPath = typeof edge.from === 'string' ? edge.from : idToNode.get(edge.from)?.path
			toPath = typeof edge.to === 'string' ? edge.to : idToNode.get(edge.to)?.path
		}
		if (!fromPath || !toPath) continue
		if (!incomingMap.has(toPath)) incomingMap.set(toPath, [])
		incomingMap.get(toPath).push(fromPath)
	}

	// 3. Union blast radius via reverse BFS
	const startPaths = new Set(mappedFiles.map((m) => m.basePath))
	const directSet = new Set()
	const indirectSet = new Set()
	const visited = new Set([...startPaths])

	const queue = []
	for (const startPath of startPaths) {
		const importers = incomingMap.get(startPath) || []
		for (const imp of importers) {
			if (!visited.has(imp)) {
				visited.add(imp)
				directSet.add(imp)
				queue.push({ path: imp, depth: 1 })
			}
		}
	}

	while (queue.length > 0) {
		const { path: curr, depth } = queue.shift()
		const nextImporters = incomingMap.get(curr) || []
		for (const imp of nextImporters) {
			if (!visited.has(imp)) {
				visited.add(imp)
				indirectSet.add(imp)
				queue.push({ path: imp, depth: depth + 1 })
			}
		}
	}

	const directList = Array.from(directSet)
	const indirectList = Array.from(indirectSet)
	const allAffected = [...directList, ...indirectList]
	const affectedCount = allAffected.length
	const percentOfRepo = totalCodeFiles > 0 ? Math.min(100, Math.round((affectedCount / totalCodeFiles) * 100)) : 0

	// Folder blast radius breakdown
	const folderMap = new Map()
	for (const node of nodes) {
		const parts = node.path.split('/')
		const folder = parts.length > 1 ? parts.slice(0, -1).join('/') : '(root)'
		if (!folderMap.has(folder)) {
			folderMap.set(folder, { total: 0, direct: 0, indirect: 0, unaffected: 0 })
		}
		const bucket = folderMap.get(folder)
		bucket.total++
		if (directSet.has(node.path)) {
			bucket.direct++
		} else if (indirectSet.has(node.path)) {
			bucket.indirect++
		} else {
			bucket.unaffected++
		}
	}

	const folderRows = []
	for (const [folder, b] of folderMap.entries()) {
		const affected = b.direct + b.indirect
		if (affected > 0) {
			folderRows.push({
				folder,
				affected,
				total: b.total,
				direct: b.direct,
				indirect: b.indirect,
				unaffected: b.unaffected,
			})
		}
	}
	folderRows.sort((a, b) => b.affected - a.affected || b.total - a.total)

	// 4. "Unchanged but affected": affected files that the PR did NOT change
	const unchangedButAffected = allAffected.filter((f) => !changedSet.has(f))

	// 5. "Will break" findings: removed or renamed files whose importers are not also changed
	const willBreakFindings = []
	for (const file of changedFiles) {
		const status = file.status
		if (status === 'removed' || status === 'renamed') {
			const oldPath = status === 'renamed' ? (file.previous_filename || file.previousPath) : (file.filename || file.path)
			if (!oldPath) continue
			const cleanOld = oldPath.replace(/^\.\//, '')
			const importers = incomingMap.get(cleanOld) || []

			for (const imp of importers) {
				if (!changedSet.has(imp)) {
					let line = null
					let snippet = `import from '${cleanOld}'`

					if (baseFiles) {
						let fileContent = baseFiles.get ? baseFiles.get(imp) : baseFiles[imp]
						if (fileContent && typeof fileContent === 'object' && fileContent.text) {
							fileContent = fileContent.text
						}
						if (typeof fileContent === 'string') {
							const lines = fileContent.split('\n')
							const baseNameNoExt = cleanOld.split('/').pop().replace(/\.[^.]+$/, '')
							for (let i = 0; i < lines.length; i++) {
								const l = lines[i]
								if (l.includes(cleanOld) || l.includes(baseNameNoExt)) {
									if (/import|require|from/i.test(l)) {
										line = i + 1
										snippet = l.trim()
										break
									}
								}
							}
						}
					}

					willBreakFindings.push({
						file: cleanOld,
						status,
						newName: status === 'renamed' ? (file.filename || file.path) : null,
						importer: imp,
						line,
						snippet,
						description: `${cleanOld} was ${status}${status === 'renamed' ? ` (renamed to ${file.filename || file.path})` : ''}, but ${imp}${line ? `:${line}` : ''} still imports it: "${snippet}"`,
					})
				}
			}
		}
	}

	// 6. Test files that import (directly or transitively) any changed file
	const isTestFile = (p) => {
		const node = pathToNode.get(p)
		if (node?.isTest) return true
		return (
			p.includes('.test.') ||
			p.includes('.spec.') ||
			p.includes('/test/') ||
			p.includes('/tests/') ||
			p.includes('/__tests__/')
		)
	}
	const testsReached = allAffected.filter(isTestFile)

	// 7. Entry points and API routes reached
	const entryPointsList = baseGraph.summary?.entryPoints || []
	const entryPointsReached = allAffected.filter((f) => entryPointsList.includes(f))

	const profileRoutes = baseGraph.summary?.profile?.routes || baseGraph.profile?.routes || []
	const routesReached = profileRoutes.filter(
		(r) => allAffected.includes(r.file) || changedSet.has(r.file)
	)

	// 8. Risk level with documented rule and reason
	let riskLevel = 'Low'
	let riskReason = `<10% of codebase blast radius (${percentOfRepo}%), no will-break findings, and no entry points reached`
	let riskRule = 'Low risk: <10% of codebase affected, 0 will-break findings, 0 entry points reached'

	if (willBreakFindings.length > 0) {
		riskLevel = 'High'
		riskReason = `${willBreakFindings.length} will-break finding(s): removed/renamed files still imported by unchanged files`
		riskRule = 'High risk: Any removed or renamed file imported by unchanged files'
	} else if (percentOfRepo > 40) {
		riskLevel = 'High'
		riskReason = `Over 40% of codebase blast radius (${percentOfRepo}%)`
		riskRule = 'High risk: Over 40% of codebase blast radius'
	} else if (entryPointsReached.length > 0 && routesReached.length > 0) {
		riskLevel = 'High'
		riskReason = `Reaches critical entry points (${entryPointsReached.length}) and API routes (${routesReached.length})`
		riskRule = 'High risk: Reaches both entry points and API routes'
	} else if (percentOfRepo >= 10) {
		riskLevel = 'Medium'
		riskReason = `10% to 40% of codebase blast radius (${percentOfRepo}%)`
		riskRule = 'Medium risk: 10% to 40% of codebase blast radius'
	} else if (entryPointsReached.length > 0 || routesReached.length > 0) {
		riskLevel = 'Medium'
		riskReason = `Reaches entry points (${entryPointsReached.join(', ') || routesReached.length + ' API routes'})`
		riskRule = 'Medium risk: Reaches entry points or API routes'
	} else if (unchangedButAffected.length > 5) {
		riskLevel = 'Medium'
		riskReason = `Affects ${unchangedButAffected.length} unchanged files`
		riskRule = 'Medium risk: Affects >5 unchanged files'
	}

	// 9. Markdown summary
	const markdownSummary = generateMarkdownSummary({
		owner,
		repo,
		pullNumber,
		riskLevel,
		riskReason,
		changedFilesCount: changedFiles.length,
		mappedFilesCount: mappedFiles.length,
		newOrUnmappedCount: newOrUnmappedFiles.length,
		affectedCount,
		totalCodeFiles,
		percentOfRepo,
		unchangedCount: unchangedButAffected.length,
		willBreakFindings,
		folderRows,
		testsReached,
		entryPointsReached,
		routesReached,
		truncated,
	})

	return {
		risk: {
			level: riskLevel,
			reason: riskReason,
			rule: riskRule,
		},
		changedFiles: {
			total: changedFiles.length,
			mappedCount: mappedFiles.length,
			newOrUnmappedCount: newOrUnmappedFiles.length,
			mapped: mappedFiles,
			newOrUnmapped: newOrUnmappedFiles,
			truncated,
		},
		blastRadius: {
			directCount: directList.length,
			indirectCount: indirectList.length,
			affectedCount,
			totalCodeFiles,
			percentOfRepo,
			direct: directList,
			indirect: indirectList,
			allAffected,
			byFolder: folderRows,
		},
		unchangedButAffected: {
			count: unchangedButAffected.length,
			files: unchangedButAffected,
		},
		willBreak: {
			count: willBreakFindings.length,
			findings: willBreakFindings,
		},
		tests: {
			count: testsReached.length,
			files: testsReached,
			message: testsReached.length > 0 ? `${testsReached.length} test files reach these changes` : 'No tests reach these files',
		},
		entryPointsReached,
		routesReached,
		markdownSummary,
	}
}

/**
 * Fetches pull request changed files from GitHub with pagination, capped at 300.
 */
async function fetchPullRequestChanges({ owner, repo, pullNumber, signal, fetchFn }) {
	const prUrl = `https://api.github.com/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repo)}/pulls/${encodeURIComponent(pullNumber)}`
	const prRes = await ghFetch(prUrl, { signal, fetchFn })
	if (prRes.status === 404) {
		const err = new Error(`Pull request #${pullNumber} not found in ${owner}/${repo}`)
		err.status = 404
		throw err
	}
	if (!prRes.ok) {
		const err = new Error(`Failed to fetch pull request #${pullNumber} from GitHub`)
		err.status = prRes.status || 502
		throw err
	}
	const prData = await prRes.json()
	const headSha = prData.head?.sha || ''
	const baseRef = prData.base?.ref || 'main'
	const baseSha = prData.base?.sha || ''
	const prTitle = prData.title || ''

	// Paginate changed files up to 300
	const changedFiles = []
	let truncated = false

	for (let page = 1; page <= 4; page++) {
		const filesUrl = `https://api.github.com/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repo)}/pulls/${encodeURIComponent(pullNumber)}/files?per_page=100&page=${page}`
		const filesRes = await ghFetch(filesUrl, { signal, fetchFn })
		if (!filesRes.ok) {
			const err = new Error(`Failed to fetch pull request files from GitHub`)
			err.status = filesRes.status || 502
			throw err
		}
		const pageFiles = await filesRes.json()
		if (!Array.isArray(pageFiles) || pageFiles.length === 0) {
			break
		}

		for (const f of pageFiles) {
			changedFiles.push({
				filename: f.filename,
				status: f.status,
				previous_filename: f.previous_filename || null,
				additions: f.additions || 0,
				deletions: f.deletions || 0,
				changes: f.changes || 0,
			})
			if (changedFiles.length >= 300) {
				truncated = true
				break
			}
		}
		if (truncated || pageFiles.length < 100) {
			break
		}
	}

	return {
		headSha,
		baseRef,
		baseSha,
		prTitle,
		changedFiles,
		truncated,
	}
}

/**
 * Fetches branch/commit comparison changed files from GitHub, capped at 300.
 */
async function fetchCompareChanges({ owner, repo, base, head, signal, fetchFn }) {
	const compareUrl = `https://api.github.com/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repo)}/compare/${encodeURIComponent(base)}...${encodeURIComponent(head)}`
	const compareRes = await ghFetch(compareUrl, { signal, fetchFn })
	if (compareRes.status === 404) {
		const err = new Error(`Comparison ${base}...${head} not found in ${owner}/${repo}`)
		err.status = 404
		throw err
	}
	if (!compareRes.ok) {
		const err = new Error(`Failed to compare ${base}...${head} on GitHub`)
		err.status = compareRes.status || 502
		throw err
	}
	const compareData = await compareRes.json()
	const headSha = compareData.commits?.[compareData.commits.length - 1]?.sha || head
	const baseRef = base
	const baseSha = compareData.base_commit?.sha || ''

	const rawFiles = compareData.files || []
	const truncated = rawFiles.length > 300
	const changedFiles = rawFiles.slice(0, 300).map((f) => ({
		filename: f.filename,
		status: f.status,
		previous_filename: f.previous_filename || null,
		additions: f.additions || 0,
		deletions: f.deletions || 0,
		changes: f.changes || 0,
	}))

	return {
		headSha,
		baseRef,
		baseSha,
		changedFiles,
		truncated,
	}
}

